export interface CountryOption {
  code: string;
  label: string;
}

export function countryName(
  code: string,
  config: PresentationConfig = defaultPresentation,
): string {
  try {
    const name = new Intl.DisplayNames([config.locale], { type: 'region' }).of(code);
    return name && name !== code ? name : code;
  } catch {
    return code;
  }
}

/** Options for an ISO alpha-2 select, sorted by display name. Built on the server so the client renders exactly the same labels. */
export function countryOptions(
  config: PresentationConfig = defaultPresentation,
): CountryOption[] {
  return ISO_3166_ALPHA2_CODES.map((code) => ({
    code,
    label: `${countryName(code, config)} (${code})`,
  })).sort((a, b) => a.label.localeCompare(b.label, config.locale));
}
